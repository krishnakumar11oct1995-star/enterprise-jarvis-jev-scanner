    # Internal API Callers
    def _call_anthropic(self, prompt: str, system: Optional[str] = None) -> str:
        headers = {
            "x-api-key": self.anthropic_key,
            "anthropic-version": "2023-06-01",
            "content-type": "application/json"
        }
        payload = {
            "model": ANTHROPIC_DEFAULT_MODEL,
            "max_tokens": 2048,
            "messages": [{"role": "user", "content": prompt}]
        }
        if system:
            payload["system"] = system

        req = urllib.request.Request(ANTHROPIC_API_URL, data=json.dumps(payload).encode("utf-8"), headers=headers, method="POST")
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        return data["content"][0]["text"]

    def _call_gemini(self, prompt: str) -> str:
        url = f"{GEMINI_API_URL}?key={self.gemini_key}"
        payload = {"contents": [{"parts": [{"text": prompt}]}]}
        req = urllib.request.Request(url, data=json.dumps(payload).encode("utf-8"), headers={"Content-Type": "application/json"}, method="POST")
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        return data["candidates"][0]["content"]["parts"][0]["text"]

    def _extract_json(self, text: str) -> Dict[str, Any]:
        """Extracts JSON block from LLM response safely."""
        import re
        match = re.search(r'```(?:json)?\s*(\{.*?\})\s*```', text, re.DOTALL)
        if match:
            return json.loads(match.group(1))
        # Try raw json search
        start = text.find("{")
        end = text.rfind("}")
        if start != -1 and end != -1:
            return json.loads(text[start:end+1])
        return {}

